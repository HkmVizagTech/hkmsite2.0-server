let pass = 0;
const fails = [];
const soft = [];
for (const r of reads) {
  const headers =
    r.auth === "internal" ? { "x-internal-secret": process.env.INTERNAL_SECRET || "local-internal-secret" } : {};
  const token = r.auth && r.auth !== "internal" ? tok[r.auth] : undefined;
  const [a, b] = await Promise.all([
    call(A, { path: r.path, token, headers }),
    call(B, { path: r.path, token, headers }),
  ]);
  const na = normalize(a.data),
    nb = normalize(b.data);
  orderOnly.length = 0;
  const problems = a.status !== b.status ? [`status ${a.status} != ${b.status}`] : diff(na, nb);
  if (orderOnly.length) soft.push(`${r.path}  (${orderOnly.join(", ")})`);
  if (problems.length) fails.push({ path: r.path, problems });
  else pass++;
  if (process.env.VERBOSE) console.log(problems.length ? "FAIL" : "ok  ", a.status, r.path);
}
console.log(`\nparity reads: ${pass}/${reads.length} identical`);
if (soft.length)
  console.log(`order-only differences (same rows, different order): ${soft.length}\n  ${soft.join("\n  ")}`);
for (const f of fails) console.log(`\nFAIL ${f.path}\n  ${f.problems.join("\n  ")}`);
process.exit(fails.length ? 1 : 0);
